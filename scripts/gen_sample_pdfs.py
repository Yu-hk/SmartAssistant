# 注册内置中文 CID 字体（Adobe STSong-Light），无需外部字体文件
pdfmetrics.registerFont(UnicodeCIDFont('STSong-Light'))
FONT = 'STSong-Light'

OUT_DIR = os.path.join(os.path.dirname(__file__), '..', 'docs', 'sample-pdfs')
os.makedirs(OUT_DIR, exist_ok=True)

styles = getSampleStyleSheet()
H1 = ParagraphStyle('H1', parent=styles['Heading1'], fontName=FONT, fontSize=18,
                    leading=24, spaceAfter=10, textColor=colors.HexColor('#1a3c6e'))
H2 = ParagraphStyle('H2', parent=styles['Heading2'], fontName=FONT, fontSize=13,
                    leading=18, spaceBefore=10, spaceAfter=6, textColor=colors.HexColor('#22577a'))
BODY = ParagraphStyle('BODY', parent=styles['BodyText'], fontName=FONT, fontSize=10.5,
                      leading=16, alignment=TA_LEFT, spaceAfter=6)
SMALL = ParagraphStyle('SMALL', parent=BODY, fontSize=9, textColor=colors.HexColor('#555555'))
CELL = ParagraphStyle('CELL', parent=BODY, fontSize=9, leading=13, spaceAfter=0)
CELLH = ParagraphStyle('CELLH', parent=CELL, textColor=colors.white, fontName=FONT)


def build(path, title, sections):
    doc = SimpleDocTemplate(path, pagesize=A4,
                            leftMargin=20 * mm, rightMargin=20 * mm,
                            topMargin=18 * mm, bottomMargin=16 * mm,
                            title=title)
    flow = [Paragraph(title, H1), Spacer(1, 4)]
    for sec in sections:
        kind = sec[0]
        if kind == 'h2':
            flow.append(Paragraph(sec[1], H2))
        elif kind == 'p':
            flow.append(Paragraph(sec[1], BODY))
        elif kind == 'spacer':
            flow.append(Spacer(1, sec[1]))
        elif kind == 'list':
            items = [ListItem(Paragraph(t, BODY), leftIndent=6) for t in sec[1]]
            flow.append(ListFlowable(items, bulletType='1', leftIndent=14))
        elif kind == 'table':
            header, rows = sec[1], sec[2]
            data = [[Paragraph(h, CELLH) for h in header]]
            for r in rows:
                data.append([Paragraph(str(c), CELL) for c in r])
            t = Table(data, colWidths=sec[3], repeatRows=1)
            t.setStyle(TableStyle([
                ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#22577a')),
                ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#9bb8d3')),
                ('VALIGN', (0, 0), (-1, -1), 'TOP'),
                ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#eef4fa')]),
                ('LEFTPADDING', (0, 0), (-1, -1), 5),
                ('RIGHTPADDING', (0, 0), (-1, -1), 5),
                ('TOPPADDING', (0, 0), (-1, -1), 3),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
            ]))
            flow.append(t)
            flow.append(Spacer(1, 6))
        elif kind == 'pagebreak':
            flow.append(PageBreak())
    doc.build(flow)
    print('generated:', path, os.path.getsize(path), 'bytes')


